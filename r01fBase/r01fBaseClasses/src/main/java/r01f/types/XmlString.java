package r01f.types;

/**
 * Just a string that contains a xml
 */
public record XmlString(String value) 
   implements CanBeRepresentedAsString {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static XmlString of(final String value) {
		return new XmlString(value);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public String asString() {
		return this.value;
	}
}
