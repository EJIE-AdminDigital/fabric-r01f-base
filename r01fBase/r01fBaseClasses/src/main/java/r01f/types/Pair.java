package r01f.types;

public record Pair<A,B>(A a,B b) {
/////////////////////////////////////////////////////////////////////////////////////////
//  CONSTRUCTOR & BUILDER
/////////////////////////////////////////////////////////////////////////////////////////
	public Pair {
		// default constructor
	}
	public static <A,B> Pair<A,B> from(final A a,final B b) {
		return new Pair<>(a,b);
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	GETTERS
/////////////////////////////////////////////////////////////////////////////////////////
	public A getA() {
		return this.a();
	}
	public B getB() {
		return this.b();
	}
}
