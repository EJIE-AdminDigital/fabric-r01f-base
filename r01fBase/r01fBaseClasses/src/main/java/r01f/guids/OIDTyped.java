package r01f.guids;

/**
 * An unique identifier backed up by a type
 * @param <T> the type that models the {@link OID} (normally a {@link String} or a {@link Long})
 */
public interface OIDTyped<T extends Comparable<? super T>> 
         extends OID {
/////////////////////////////////////////////////////////////////////////////////////////
//  ABSTRACT METHODS
/////////////////////////////////////////////////////////////////////////////////////////
	public T getId();
/////////////////////////////////////////////////////////////////////////////////////////
//  
/////////////////////////////////////////////////////////////////////////////////////////
	/**
	 * Returns the raw value encapsulated by the OID
	 * @return the raw value
	 */
	public default T getRaw() {
		return this.getId();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	EQUALS
/////////////////////////////////////////////////////////////////////////////////////////
	/**
	 * Returns true if the underlying id equals the provided one
	 * @param otherId
	 * @return
	 */
	public default boolean is(final T otherId) {
		if (otherId == null) return false;
		if (otherId == this.getId()) return true;
		return otherId.equals(this.getId());
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	CanBeRepresentedAsString
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public default String asString() {
		return this.toString();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	VALID
/////////////////////////////////////////////////////////////////////////////////////////
	@Override
	public default boolean isValid() {
		return this.getId() != null;
	}
}
