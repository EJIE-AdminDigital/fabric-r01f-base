package r01f.model.security;

import lombok.RequiredArgsConstructor;
import lombok.experimental.Accessors;
import r01f.enums.EnumExtended;

@Accessors(prefix="_")
@RequiredArgsConstructor
public enum LoginStatus
 implements EnumExtended<LoginStatus> {
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	ACTIVE,
	PENDING_ADMIN_APROVAL,
	PENDING_PRINCIPAL_DATA,
	INACTIVE;
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static final boolean canBe(final String name) {
		return EnumExtended.canBeFromName(name,LoginStatus.class);
	}
}
