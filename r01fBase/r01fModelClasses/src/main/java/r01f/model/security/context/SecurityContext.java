package r01f.model.security.context;

import java.io.Serializable;
import java.time.Instant;

import com.google.common.reflect.TypeToken;

import r01f.model.security.IsSecurityPrincipal;
import r01f.model.security.IsSecurityPrincipalDataForPerson;
import r01f.oids.CommonOIDs.AppCode;
import r01f.oids.CommonOIDs.AppComponent;
import r01f.oids.CommonOIDs.TenantID;
import r01f.oids.SecurityIDs.SecurityPrincipalID;
import r01f.oids.SecurityIDs.SecurityToken;
import r01f.oids.SecurityOIDs.SecurityPrincipalOID;

/**
 * Marker interface for every user context data
 */
public interface SecurityContext
		 extends Serializable {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////
	/**
	 * The [security context] creation date
	 * @return
	 */
	public Instant getCreatedAt();
/////////////////////////////////////////////////////////////////////////////////////////
//	VALID
/////////////////////////////////////////////////////////////////////////////////////////	
	/**
	 * Whether the [security context] is valid or not (if it has been invalidated)
	 */
	public boolean isValid();
	/**
	 * Invalidates the [security context] so it can't be used anymore
	 */
	public void invalidate();
	/**
	 * A signed token that proves that this [security context] was generated by a legitimate system
	 */
	public SecurityToken getValidationToken();
/////////////////////////////////////////////////////////////////////////////////////////
//	TENANT
/////////////////////////////////////////////////////////////////////////////////////////	
	/**
	 * The tenant id
	 */
	public TenantID getTenantId();
/////////////////////////////////////////////////////////////////////////////////////////
//	SECURITY PRINCIPAL
/////////////////////////////////////////////////////////////////////////////////////////	
	public IsSecurityPrincipal getSecurityPrincipal();
	
	@SuppressWarnings("unchecked")
	public default <P extends IsSecurityPrincipal> P getSecurityPrincipalAs(final Class<P> type) {
		return (P)this.getSecurityPrincipal();
	}
	@SuppressWarnings("unchecked")
	public default <P extends IsSecurityPrincipal> P getSecurityPrincipalAs(final TypeToken<P> type) {
		return (P)this.getSecurityPrincipal();
	}
	
	public default SecurityPrincipalOID getSecurityPrincipalOid() {
		return this.getSecurityPrincipal() != null ? this.getSecurityPrincipal().getOid()
											   	   : null;
	}
	public default SecurityPrincipalID getSecurityPrincipalId() {
		return this.getSecurityPrincipal() != null ? this.getSecurityPrincipal().getId()
											   	   : null;
	}
////////// --- SYSTEM SECURITY PRINCIPAL	
	public boolean isForSystemSecurityPrincipal();
	
////////// --- PERSON SECURITY PRINCIPAL	
	public boolean isForPersonSecurityPrincipal();
	public <D extends IsSecurityPrincipalDataForPerson,S extends SecurityContextForPerson<D>> S asForPersonSecurityPrincipal(final Class<S> type);
	
	public interface SecurityContextForPerson<D extends IsSecurityPrincipalDataForPerson> 
		     extends SecurityContext {
		public D getPersonData();
	}
////////// --- CLIENT APP SECURITY PRINCIPAL
	public boolean isForClientAppSecurityPrincipal();
	public <S extends SecurityContextForClientApp> S asForClientAppSecurityPrincipal(final Class<S> type);
	
	public interface SecurityContextForClientApp 
		     extends SecurityContext {
		
		public AppCode getAppCode();
		public AppComponent getAppComponent();
	}
	
/////////////////////////////////////////////////////////////////////////////////////////
//	IMPERSONATION
/////////////////////////////////////////////////////////////////////////////////////////	
	public SecurityPrincipalOID getImpersonatingSecurityPrincipalOid();
	public void setImpersonatingSecurityPrincipalOid(final SecurityPrincipalOID impersonatedSecurityPrincipalOid);
	
	public default boolean isBeingImpersonated() {
		return this.getImpersonatingSecurityPrincipalOid() != null;
	}

/////////////////////////////////////////////////////////////////////////////////////////
//	CASTING
/////////////////////////////////////////////////////////////////////////////////////////
	@SuppressWarnings("unchecked")
	public default <CTX extends SecurityContext> CTX as(final Class<CTX> type) {
		return (CTX)this;
	}
}
