package r01f.model.security;

import lombok.RequiredArgsConstructor;
import lombok.experimental.Accessors;
import r01f.enums.EnumExtended;

@Accessors(prefix="_")
@RequiredArgsConstructor
public enum SecurityPrincipalStatus
 implements EnumExtended<SecurityPrincipalStatus> {
/////////////////////////////////////////////////////////////////////////////////////////
//
/////////////////////////////////////////////////////////////////////////////////////////
	ACTIVE,
	PENDING_ADMIN_APROVAL,
	PENDING_DATA_COMPLETION,
	INACTIVE;
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public static final boolean canBe(final String name) {
		return EnumExtended.canBeFromName(name,SecurityPrincipalStatus.class);
	}
}
