/**
 * The [security principal] is an entity created and managed within an [identity provider] like Giltza, Google, XLNets... (or [identity broker] such as Keycloak or WSO2 Identity Server).
 * Its primary purpose is to act as the main entity subject of:
 * 		- Authentication
 * 		- Authorization. 
 * 
 * When the system allows authentication through various external [identity providers] (such as Google, Giltza/Izenpe, etc.), usually an [Identity Broker] (KeyCloak) is used
 *  *  
 * It's also important to note that the concept of a [Person] is NOT the same as the concept of a [security principal] 
 * 		- [Person] 
 * 			- refers to an individual related with the business domain (a citizen, a user, a customer, etc.) and is represented in the system's operational database.
 * 			- It's managed by the business logic
 * 			- It's not directly tied to the [authentication] or [authorization] processes.
 * 
 * 		- [Security Principal] 
 * 			- refers to the subject of [authentication] (authn) or [authorization] (authz)
 * 			- It's managed by the [identity provider] or [identity broker] .
 * 			- It can be:
 * 					- a [person]
 * 					- a [service] (an app, a process, a microservice, etc.)
 * 					- an [organization]
 * 
 * BEWARE!!!!
 * 		Only if the [security principal] is a [person], there's a link between the [Person] in the business domain and the [security principal] in the security domain.
 * 
 * Structure and Minimal Data of a [security principal]
 * #####################################################
 * [1] - [identity provider]-assigned ID: {@link SecurityPrincipalID}
 * ---------------------------------------------------------------
 * An ID linked to a [security principal] that usually:
 *  - It's linked to a business concept like an EMail, a PersonID, a Phone, etc (it's not an OID)
 *   		- Google uses the EMail
 *   		- Giltza uses the PersonID
 *   		- etc
 * 	- Is unique 
 * The [security principal] OID is a randomly generated OID by the [identity provider] or [identity broker]
 * 
 * Usually in the [authorization] process, in the first moment, just the [security principal] ID is known 
 * and that ID is used to retrieve the full [security principal] data from the [identity provider] or [identity broker]
 * that contains the [security principal] OID and other data 
 *
 * Examples:
 *		- Giltza: id = user's DNI/NIE from their digital certificate.
 *		- Google: id = user's email address or Google Account ID.
 *
 * Function: It tracks the external source where the [principal] came from, validating their original authenticity every time they log in.
 *  
 * [2] - [Identity Provider] (or [Identity Broker]) -assigned OID
 * --------------------------------------------------------------
 * What it is: An [universal unique identifier] (UUID) internally generated by the [Identity Broker] itself (for example, the internal user_id assigned by Keycloak).
 *
 * Function: It is used to manage the technical security session, access tokens, and refresh tokens within the security architecture.
 *
 * [3] - Data that depends on the [principal] nature 
 * -------------------------------------------------------------
 * 3.1) - If the [security principal] is a [person]
 * 		  		The [security principal] contains the {@link IsPersonOID} that "links" the [security principal] to the actual [person] in the business domain.
 * 
 * 3.2) - If the [security principal] is a [service] (an app, a process, a microservice, etc.)
 * 				The appCode, serviceCode, or microserviceCode is used to identify the [security principal] in the business domain.
 */
public interface IsSecurityPrincipal
		 extends HasSystemWideRoles,
		 		 IsSecurityPersistableObjectWithID<SecurityPrincipalOID,SecurityPrincipalID>,
		 		 HasLangIndependentDisplayName {
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
////////// --- IDENTITY PROVIDER WHERE THE [SECURITY PRINCIPAL] COMES FROM
	public IdentityProvider getSourceIdentityProvider();
	public void setSourceIdentityProvider(final IdentityProvider identityProvider);
	
////////// --- STATUS
	public SecurityPrincipalStatus getStatus();
	public void setStatus(final SecurityPrincipalStatus status);
	
////////// --- DISPLAY NAME
	public default String getDisplayNameIn(final Language lang) {
		return this.getDisplayName();
	}
////////// --- SECURITY PRINCIPAL
	public default SecurityPrincipalOID getSecurityPrincipalOid() {
		return this.getOid();
	}
	public default SecurityPrincipalID getSecurityPrincipalId() {
		return this.getId();
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////
	@SuppressWarnings("unchecked")
	public default <P extends IsSecurityPrincipal> P as(final Class<P> type) {
		return (P)this;
	}
	@SuppressWarnings("unchecked")
	public default <P extends IsSecurityPrincipal> P as(final TypeToken<P> type) {
		return (P)this;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	UPDATE
/////////////////////////////////////////////////////////////////////////////////////////	
	/**
	 * Checks if the [security principal] has changed compared to the given one
	 * @param <P>
	 * @param other
	 * @return
	 */
	public <P extends IsSecurityPrincipal> boolean hasDifferentDataTo(final P other);
	/**
	 * Updates the [security principal] data from the given one
	 * returns true if any field was updated; false otherwise
	 * @param other
	 */
	public <P extends IsSecurityPrincipal> void updateFrom(final P other);
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////
	public default <C extends IsContactMean> boolean hasContactMean(final C contactMean) {
		if (contactMean instanceof EMail email) {
			return this.hasEMail(email);
		} else if (contactMean instanceof Phone phone) {
			return this.hasPhoneNumber(phone);
		}
		throw new IllegalArgumentException(Strings.customized("'{}' is not a {} or {} instance",
				 											   this.getClass(),EMail.class,Phone.class));
	}
	@SuppressWarnings("unchecked")
	public default <C extends IsContactMean> C getDefaultContactMeanOrAny(final Class<? extends IsContactMean> contactMeanType) {
		if (EMail.class.isAssignableFrom(contactMeanType)) {
			return (C)this.getDefaultEMailOrAny();
		} else if (Phone.class.isAssignableFrom(contactMeanType)) {
			return (C)this.getDefaultPhoneNumberOrAny();
		}
		throw new IllegalArgumentException(Strings.customized("'{}' is not a {} or {} instance",
				 											   this.getClass(),EMail.class,Phone.class));
	}
	@SuppressWarnings("unchecked")
	public default <C extends IsContactMean> C getDefaultContactMeanOrNull(final Class<? extends IsContactMean> contactMeanType) {
		if (EMail.class.isAssignableFrom(contactMeanType)) {
			return (C)this.getDefaultEMailOrNull();
		} else if (Phone.class.isAssignableFrom(contactMeanType)) {
			return (C)this.getDefaultPhoneNumberOrNull();
		}
		throw new IllegalArgumentException(Strings.customized("'{}' is not a {} or {} instance",
				 											   this.getClass(),EMail.class,Phone.class));
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public default boolean hasEMail(final EMail email ) {
		if (!(this instanceof HasEMailAddress)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					  this.getClass(),HasEMailAddress.class));
		boolean hasEmail = false;
		if (this instanceof HasContactEMails hasContactEMails) {
			hasEmail = hasContactEMails.hasEMailAddress(email);
		} else if (this instanceof HasEMailAddresses hasEMailAddreses) {
			hasEmail = hasEMailAddreses.hasEMailAddress(email);
		} else {
			EMail principalEMail = ((HasEMailAddress)this).getEMailAddress();
			hasEmail = principalEMail != null 
				    && principalEMail.is(email);
		}
		return hasEmail;
	}
	public default EMail getDefaultEMailOrAny() {
		 if (!(this instanceof HasEMailAddress)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					   this.getClass(),HasEMailAddress.class));
		 EMail principalEmail = null;
		 if (this instanceof HasContactEMails hasContactEMails) {
			 principalEmail = hasContactEMails.getDefaultEMailAddressOrAny();
		 } else {
			 principalEmail = ((HasEMailAddress)this).getEMailAddress();
		 }
		 return principalEmail;
	}
	public default EMail getDefaultEMailOrNull() {
		 if (!(this instanceof HasEMailAddress)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					   this.getClass(),HasEMailAddress.class));
		 EMail principalEmail = null;
		 if (this instanceof HasContactEMails hasContactEMails) {
			 principalEmail = hasContactEMails.getDefaultEMailAddress();	// null if no default email is set
		 } else {
			 principalEmail = ((HasEMailAddress)this).getEMailAddress();
		 }
		 return principalEmail;
	}
/////////////////////////////////////////////////////////////////////////////////////////
//	
/////////////////////////////////////////////////////////////////////////////////////////	
	public default boolean hasPhoneNumber(final Phone phone ) {
		if (!(this instanceof HasPhoneNumber)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					 this.getClass(),HasPhoneNumber.class));
		boolean hasPhone = false;
		if (this instanceof HasContactPhones hasContactPhones) {
			hasPhone = hasContactPhones.hasPhoneNumber(phone);
		} else if (this instanceof HasPhoneNumbers hasPhoneNumbers) {
			hasPhone = hasPhoneNumbers.hasPhoneNumber(phone);
		} else {
			Phone principalPhone = ((HasPhoneNumber)this).getPhoneNumber();
			hasPhone = principalPhone != null 
				    && principalPhone.is(phone);
		}
		return hasPhone;
	}
	public default Phone getDefaultPhoneNumberOrAny() {
		if (!(this instanceof HasPhoneNumber)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					 this.getClass(),HasPhoneNumber.class));
		Phone principalPhone = null;
		if (this instanceof HasContactPhones hasContactPhones) {
			principalPhone = hasContactPhones.getDefaultPhoneNumberOrAny();
		} else {
			principalPhone = ((HasPhoneNumber)this).getPhoneNumber();
		}
		return principalPhone;
	}
	public default Phone getDefaultPhoneNumberOrNull() {
		if (!(this instanceof HasPhoneNumber)) throw new IllegalArgumentException(Strings.customized("type '{}' is not a {} instance",
				 																					 this.getClass(),HasPhoneNumber.class));
		Phone principalPhone = null;
		if (this instanceof HasContactPhones hasContactPhones) {
			principalPhone = hasContactPhones.getDefaultPhoneNumber();		// null if no default phone is set
		} else {
			principalPhone = ((HasPhoneNumber)this).getPhoneNumber();
		}
		return principalPhone;
	}	
}
