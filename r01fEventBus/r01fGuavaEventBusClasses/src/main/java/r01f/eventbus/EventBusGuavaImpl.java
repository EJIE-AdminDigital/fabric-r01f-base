package r01f.eventbus;

public class EventBusGuavaImpl 
  implements EventBus {
/////////////////////////////////////////////////////////////////////////////////////////
//	FIELDS
/////////////////////////////////////////////////////////////////////////////////////////    
    private final com.google.common.eventbus.EventBus _eventBus;
/////////////////////////////////////////////////////////////////////////////////////////
// CONSTRUCTOR
/////////////////////////////////////////////////////////////////////////////////////////
    public EventBusGuavaImpl(){
    	_eventBus  = new  com.google.common.eventbus.EventBus();
    }    
    public EventBusGuavaImpl(final  com.google.common.eventbus.EventBus eventBus){
    	_eventBus  = eventBus;
    }        
/////////////////////////////////////////////////////////////////////////////////////////
//  METHODS TO IMPLEMENT
/////////////////////////////////////////////////////////////////////////////////////////
    @Override
    public void post(final Event event) {    
    	_eventBus.post(event);
    }
    @Override
    public void register(final EventBusListener listener) {   
    	_eventBus.register(listener); 
    }
}
